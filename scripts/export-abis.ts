/** Export Foundry ABIs + bytecode hashes into a typed TS module consumed by SDK, services and web. */
import { readFileSync, writeFileSync } from 'node:fs';
import { keccak256 } from 'viem';
import { canonicalize } from '../packages/domain/src/canonical';

const NAMES = ['JobRegistry', 'WorkflowExecutionRegistry', 'EvidenceRegistry'] as const;
let out = '// Generated by scripts/export-abis.ts from contracts/evm/out. Do not edit.\n';
const meta: Record<string, unknown> = {};
for (const n of NAMES) {
  const art = JSON.parse(readFileSync(`contracts/evm/out/${n}.sol/${n}.json`, 'utf8'));
  out += `export const ${n}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
  meta[n] = {
    abiHash: keccak256(new TextEncoder().encode(canonicalize(art.abi))),
    artifactRuntimeHash: keccak256(art.deployedBytecode.object),
    initCodeHash: keccak256(art.bytecode.object),
    bytecodeBytes: (art.bytecode.object.length - 2) / 2,
    compiler: JSON.parse(art.rawMetadata ?? '{}')?.compiler?.version ?? null,
  };
}
out += `export const CONTRACT_ARTIFACT_META = ${JSON.stringify(meta, null, 2)} as const;\n`;
writeFileSync('packages/domain/src/abis.generated.ts', out);
console.log(JSON.stringify(meta, null, 2));
